def render(tmpl, r, extra=None):
    """只替换模板中真实出现的占位符，避免对未使用的复杂值做 join 而报错。"""
    ctx = dict(r)
    if extra:
        ctx.update(extra)
    s = tmpl
    for k in set(re.findall(r"\{(\w+)\}", tmpl)):
        v = ctx.get(k, "")
        if isinstance(v, list):
            v = "\n".join(str(x) for x in v)
        s = s.replace("{" + k + "}", str(v))
    return s


def bullets(items, prefix="1. "):
    out = []
    for i, x in enumerate(items):
        if prefix.strip().endswith("."):
            out.append(f"{i + 1}. {x}")
        else:
            out.append(f"{prefix} {x}")
    return out


