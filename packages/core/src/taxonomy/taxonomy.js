export const ALL_TAGS = [...TOPIC_TAGS, ...COPY_TAGS, ...RHYTHM_TAGS, ...CRAFT_TAGS];

export const TAG_INDEX = new Map(ALL_TAGS.map((t) => [t.id, t]));

export function getTag(id) {
  return TAG_INDEX.get(id) || null;
}

export function tagsByDimension(dimension) {
  return ALL_TAGS.filter((t) => {
    if (dimension === 'topic') return TOPIC_TAGS.includes(t);
    if (dimension === 'copy') return COPY_TAGS.includes(t);
    if (dimension === 'rhythm') return RHYTHM_TAGS.includes(t);
    if (dimension === 'craft') return CRAFT_TAGS.includes(t);
    return false;
  });
}

/**
 * 关键词匹配打分：命中词数 + 权重 -> 置信度 0~1
 */
export function scoreByKeywords(text, keywords, weight = 1) {
  if (!keywords || !keywords.length) return { hits: 0, confidence: 0, matched: [] };
  const t = String(text || '');
  const matched = keywords.filter((k) => t.includes(k));
  if (!matched.length) return { hits: 0, confidence: 0, matched: [] };
  const raw = Math.min(1, (matched.length / 2) * weight);
  return { hits: matched.length, confidence: Number(raw.toFixed(2)), matched };
}

/** 导出完整标签体系（供 API 与前端消费） */
export function exportTaxonomy() {
  return {
    dimensions: Object.values(DIMENSIONS),
    groups: [
      { id: 'topic', name: '题材', tags: TOPIC_TAGS.map(strip) },
      { id: 'copy', name: '文案', tags: COPY_TAGS.map(strip) },
      { id: 'rhythm', name: '节奏', tags: RHYTHM_TAGS.map(strip) },
      { id: 'craft', name: '表现手法', tags: CRAFT_TAGS.map(strip) },
    ],
    total: ALL_TAGS.length,
  };
}

function strip(t) {
  return { id: t.id, name: t.name, desc: t.desc, keywords: t.keywords };
}
